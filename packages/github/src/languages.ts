export function languageBreakdown(data: Record<string, number>) {
  const entries = Object.entries(data)
    .filter(([, n]) => Number.isFinite(n) && n > 0)
    .sort((a, b) => b[1] - a[1])
  const total = entries.reduce((s, [, n]) => s + n, 0)
  const top = entries.slice(0, 6).filter(([, n]) => n / total >= 0.006)
  const rest = entries.slice(top.length).reduce((s, [, n]) => s + n, 0)
  if (rest) top.push(['Other', rest])
  return top.map(([name, n]) => ({ name, percent: (100 * n) / total, color: colors[name.toLowerCase()] ?? '#8b949e' }))
}
